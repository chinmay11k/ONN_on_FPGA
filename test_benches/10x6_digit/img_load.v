`timescale 1ns / 1ps
module img_load_10(
    input [3:0] img_no,
    input start,
    input re,
    input sclk,
    output reg data_in,
    output reg load
);

reg [0:239] state;
reg [7:0] c=0;

always @(posedge sclk) begin
    if (re == 1) begin
        load <= 0;
        c <= 0;
        case (img_no)
        0:state<=240'h800008_808808_008800_008800_088880_088880_008800_008800_808808_800008;
        1:state<=240'h880088_800088_000088_880088_880088_880088_880088_880088_000000_000000;
        2:state<=240'h800008_000000_008800_888800_888800_888008_880088_800888_000000_000000;
        3:state<=240'h800008_088800_888800_888000_880008_880008_888000_888800_088800_800008;
        4:state<=240'h888808_888008_880008_800808_008808_088808_000000_888808_888808_888808;
        5:state<=240'h000000_000000_008888_000088_000008_888800_888800_088800_000000_800008;
        6:state<=240'h888000_880008_800088_000888_000008_000000_008800_008800_000000_800008;
        7:state<=240'h000000_000000_888800_888008_888008_880088_880088_800888_800888_800888;
        8:state<=240'h880088_800008_008800_008800_800008_800008_008800_008800_800008_880088;//new
        9:state<=240'h800008_000000_008800_008800_000000_800000_888000_880008_800088_000888;//new
//        8:state<=240'h800008_000000_008800_008800_800008_800008_008800_008800_000000_800008;//old 8
//        9:state<=240'h800008_000000_008800_008800_000000_800000_888800_008800_000000_800008;//old 9
        endcase
    end
    else if (start == 1) begin
        if (c <240) begin
            load <= 1;
            data_in <= state[239];         // Send MSB first
            state <= state >> 1;          // Left shift by 1
            c <= c + 1;
        end
        else begin
            load <= 0;
        end
    end
    else begin
        load <= 0;
    end
end

endmodule
