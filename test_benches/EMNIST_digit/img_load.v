`timescale 1ns/1ps

module img_load (
    input        sclk,
    input        re,
    input        start,

    input        digit,       // 0 or 1
    input  [2:0]  img_no,     // 0 to 4

    output reg   data_in,
    output reg   load
);

reg [399:0] state;
reg [8:0]   c;

always @(posedge sclk) begin

    // Load selected image
    if (re) begin

        c    <= 0;
        load <= 0;

        case (digit)

            // DIGIT 0

            1'b0: begin

                case (img_no)

                    3'd0:
                        state <= 400'h8888877888888842788888840124888861546148871588852884288886288258888438823888517887123226888876668888;

                    3'd1:
                        state <= 400'h8888768888888500278888304502888604885048840688803884078870588307882188850251178888410278888888888888;

                    3'd2:
                        state <= 400'h8888888888888733788888720015888710563038830688820781388884188126776048850000057888422268888888888888888;

                    3'd3:
                        state <= 400'h8888888888888722688888822526888851785188871488738885178872888618883388870352288888621378888888888888888;

                    3'd4:
                        state <= 400'h8888888888888636888888500223788703764038851888850882387883288328884078860462068888621268888888788888;

                    default:
                        state <= 400'h0;

                endcase
            end


            // DIGIT 1

            1'b1: begin

                case (img_no)

                    3'd0:
                        state <=400'h8888877888888871588888885078888888338888888815888888871688888887078888888606888888860688888888788888;

                    3'd1:
                        state <= 400'h8888888888888883388888888128888888713888888850388888882068888887028888888405888888843888888888888888;

                    3'd2:
                        state <= 400'h8888778888888844888888883588888888268888888825888888883488888888348888888842888888886288888888878888;

                    3'd3:
                        state <= 400'h8888788888888628888888851888888884388888888158888888815888888871785788886288678888628888888887888888;

                    3'd4:
                        state <= 400'h8888888888888855888888884078888888507888888850788888885078888888407888888820788888884488888888888888;

                    default:
                        state <= 400'h0;

                endcase
            end

        endcase
    end

    else if (start) begin

        if (c < 400) begin

            load    <= 1'b1;
            data_in <= state[399];

            // MSB first
            state <= state >> 1;

            c <= c + 1'b1;

        end
        else begin

            load <= 1'b0;

        end
    end

    else begin
        load <= 1'b0;
    end

end

endmodule